import os

MAP = ["TTTTTTTTTTTTTTT", "T.............T", "T..HH.....gg..T", "T..HH.....ggg.T", "T..==.....gg..T",
       "T..=N=........T", "T..===........T", "T.....==......T", "T.gg....=.....T", "Tggg....==..~~T",
       "Tgg......=..~~T", "T........=gg.~T", "T..gggg..=ggg.T", "T..gggg..=....T", "T..ggg...==...T",
       "T........=....T", "T.........=...T", "TTTTTTTTTTTTTTT"]


def route(a, b):
    """BFS over path and plain grass (no tall grass), like html_shots.js."""
    prev, q = {a: None}, [a]
    while q:
        x, y = q.pop(0)
        if (x, y) == b:
            break
        for dx, dy, k in [(0, -1, "up"), (0, 1, "down"), (-1, 0, "left"), (1, 0, "right")]:
            n = (x + dx, y + dy)
            if MAP[n[1]][n[0]] in ".=" and n not in prev:
                prev[n] = (x, y, k)
                q.append(n)
    ks, c = [], b
    while prev[c]:
        p = prev[c]
        ks.insert(0, p[2])
        c = (p[0], p[1])
    return ks


